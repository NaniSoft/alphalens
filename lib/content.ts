/**
 * The six numbered sections, as data.
 *
 * The index, the label and the honesty status are three separate fields because they are
 * three separate things: the index is a number that says where in the reading order this
 * sits, the label is the section's name, and the status is a claim about what the section
 * may say. A Block takes the index as its `eyebrow` and the label *with* the status as its
 * title, so nothing in the markup has to concatenate them and the rendered `h2` is the
 * string below.
 *
 * The status is inside the label on purpose and there is no field beside it. A badge, a
 * count or a collapse control next to a section whose title carries a status would each
 * say the sections are independent topics a reader may visit in any order, and four of
 * these six are a pipeline where that is exactly wrong. A status in the title is content;
 * a badge beside it is a claim about the section's state.
 *
 * The index is also a reading order and not decoration. Six sections that describe one
 * pipeline in sequence are a table of contents with a border around it, and the number is
 * the one thing that says so.
 */
