/** A section's rendered title: its label with its status in parentheses, or the label alone. */
export function sectionTitle(index: number): string {
  const section = SECTIONS[index];
  if (!section) throw new Error(`no section at index ${index}, so a reader would be shown a heading with no section behind it`);
  return section.status ? `${section.label} (${section.status})` : section.label;
}

